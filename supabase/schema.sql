-- Task 3: automation requests. Ownership is enforced by PostgreSQL RLS.
create table if not exists public.automation_requests (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null check (char_length(btrim(title)) between 1 and 150),
  description text not null check (char_length(btrim(description)) between 1 and 20000),
  category text not null check (category in ('Бот','Интеграция','Отчёт','Другое')),
  status text not null default 'Новая' check (status in ('Новая','В работе','Завершена')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_automation_requests_owner_created
  on public.automation_requests (owner_id, created_at desc);
create index if not exists idx_automation_requests_owner_status
  on public.automation_requests (owner_id, status);
alter table public.automation_requests enable row level security;
-- WITH CHECK prevents writing another owner's ID and enforces New status at creation.
drop policy if exists requests_select_own on public.automation_requests;
create policy requests_select_own on public.automation_requests
  for select to authenticated using (owner_id = (select auth.uid()));
drop policy if exists requests_insert_own on public.automation_requests;
create policy requests_insert_own on public.automation_requests
  for insert to authenticated with check (owner_id = (select auth.uid()) and status = 'Новая');
drop policy if exists requests_update_own on public.automation_requests;
create policy requests_update_own on public.automation_requests
  for update to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));
-- No DELETE policy => end users cannot delete requests.
grant usage on schema public to authenticated;
grant select, insert, update on public.automation_requests to authenticated;
revoke all on public.automation_requests from anon;

-- Task 1: a deliberately public READ-ONLY demo catalog. Never store secrets here.
create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
alter table public.services enable row level security;
drop policy if exists services_public_read on public.services;
create policy services_public_read on public.services
  for select to anon, authenticated using (true);
grant select on public.services to anon, authenticated;
revoke insert, update, delete on public.services from anon, authenticated;
